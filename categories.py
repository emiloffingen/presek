def detect_category(title: str, description: str = "", source: str = "") -> str:
    if source in ALBANIAN_SOURCES:
        return "Албански"
    text = (title + " " + description).lower()
    for cat_name, keywords in CATEGORIES:
        if any(kw in text for kw in keywords):
            return cat_name
    return "Општо"


